// HABITAT 类群 → 卡面色带（色相区分 + 与地图园区色呼应）
export const HABITAT = {
  Predator: { zh: '猛兽区', en: 'Predator', color: '#e2a05c' },
  Herbivore: { zh: '食草区', en: 'Herbivore', color: '#8bc34a' },
  Primate: { zh: '灵长区', en: 'Primate', color: '#c98bcd' },
  Reptile: { zh: '爬行馆', en: 'Reptile', color: '#7cb9a8' },
  Bird: { zh: '鸟舍', en: 'Aviary', color: '#6da8d6' },
  Pet: { zh: '宠物角', en: 'Petting zoo', color: '#e6b8c4' },
};

// habitatOf 动物按标签映射类群色带（宠物优先）
export function habitatOf(a) {
  if (a.pz) return HABITAT.Pet;
  for (const k of ['Primate', 'Reptile', 'Bird', 'Predator', 'Herbivore']) {
    if (a.tg.includes(k)) return HABITAT[k];
  }
  return HABITAT.Herbivore;
}

